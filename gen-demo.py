#!/usr/bin/env python3
"""Generate demo.html from index.html.

demo.html is index.html plus a banner and a loader that feeds demo.fit into
the dropzone on page load, so the tool comes up already populated.  It is
generated rather than hand-maintained so the two pages cannot drift apart --
re-run this (or `just demo`) after editing index.html.
"""

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))

BANNER_STYLE = """
  <style>
    /* demo.html only -- not part of the production stylesheet */
    .demo-banner {
      background: var(--accent-soft);
      border: 1px solid var(--border-strong);
      border-radius: 6px;
      padding: 0.6rem 0.9rem;
      margin-bottom: 1.5rem;
      font-size: 0.85rem;
      color: var(--text-muted);
      text-align: center;
    }
    .demo-banner strong { color: var(--accent); }
    .demo-banner a { color: var(--accent); }
  </style>
"""

BANNER_HTML = """    <div class="demo-banner">
      <strong>Demo page.</strong> A signed sample image (<a href="demo.fit" download>demo.fit</a>)
      is loaded automatically &mdash; no need to drop a file.
      The real tool lives at <a href="index.html">index.html</a>.
    </div>
"""

LOADER_SCRIPT = """
  <script>
  // demo.html only: feed demo.fit to the dropzone as if it had been dropped.
  (async () => {
    const dropzone = document.getElementById('dropzone');
    const errorBox = document.getElementById('error-box');

    function fail(msg) {
      errorBox.textContent = 'Demo: ' + msg;
      errorBox.classList.remove('hidden');
    }

    if (location.protocol === 'file:') {
      fail('open this page over HTTP (e.g. `just serve`); fetch() is blocked on file:// URLs.');
      return;
    }

    try {
      const res = await fetch('demo.fit');
      if (!res.ok) throw new Error(res.status + ' ' + res.statusText);
      const data = await res.arrayBuffer();

      const dt = new DataTransfer();
      dt.items.add(new File([data], 'demo.fit'));
      dropzone.dispatchEvent(new DragEvent('drop', {
        dataTransfer: dt,
        bubbles: true,
        cancelable: true,
      }));
    } catch (e) {
      fail('could not load demo.fit — ' + e.message);
    }
  })();
  </script>
"""


def generate(src, dst):
    html = open(src, encoding='utf-8').read()

    if '<title>' not in html or '</body>' not in html:
        sys.exit(f'{src}: unexpected structure, cannot generate demo page')

    html = html.replace(
        '<title>fitfall.de',
        '<title>Demo — fitfall.de', 1)
    html = html.replace(
        '  <meta name="color-scheme" content="light">\n',
        '  <meta name="color-scheme" content="light">\n'
        '  <meta name="robots" content="noindex">\n', 1)
    html = html.replace('</head>', BANNER_STYLE + '</head>', 1)
    html = html.replace(
        '  <div class="container">\n',
        '  <div class="container">\n' + BANNER_HTML, 1)
    html = html.replace('</body>', LOADER_SCRIPT + '</body>', 1)

    header = ('<!-- GENERATED by gen-demo.py from index.html — do not edit'
              ' directly. -->\n')
    open(dst, 'w', encoding='utf-8').write(header + html)
    return dst


if __name__ == '__main__':
    out = generate(os.path.join(_HERE, 'index.html'),
                   os.path.join(_HERE, 'demo.html'))
    print(f'Wrote {out}')
